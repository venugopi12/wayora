import type { ActivityCategory, CostLevel, PlanningGroup, TimeOfDay } from '@wayora/contracts';

/*
 * Curated SAMPLE planning data (docs/planner.md#recommendations).
 *
 * Hand-written by the Wayora team for demonstration: well-known places and
 * experiences for the twelve sample destinations of the discover pages (same
 * ids). It is not a places provider and it is never refreshed:
 *
 * - No opening hours, prices, availability, ratings or travel times. Only a
 *   rough cost level, a planning estimate of how long to allow and when an
 *   activity is commonly enjoyed — all labelled as estimates in the UI.
 * - Summaries describe what the place is, not current conditions. Seasonal or
 *   access caveats say "check before you go" rather than stating a schedule.
 *
 * Suggestion ids are `<destination>:<activity>` and are stored on itinerary
 * items, so existing ids must never be renamed or reused for another place.
 */

export type Intensity = 'easy' | 'active';

export interface CatalogActivity {
  /** `<destination>:<slug>`. */
  id: string;
  title: string;
  category: ActivityCategory;
  area: string;
  summary: string;
  /** Planning estimate: how long to allow, in minutes. */
  typicalMinutes: number;
  costLevel: CostLevel;
  bestTime: TimeOfDay;
  intensity: Intensity;
  /** Who it typically suits. */
  groups: readonly PlanningGroup[];
}

export interface CatalogDestination {
  id: string;
  name: string;
  country: string;
  timeZone: string;
  activities: readonly CatalogActivity[];
}

const ALL: readonly PlanningGroup[] = ['solo', 'couple', 'family', 'friends'];
const ADULTS: readonly PlanningGroup[] = ['solo', 'couple', 'friends'];

type Row = [
  slug: string,
  title: string,
  category: ActivityCategory,
  area: string,
  typicalMinutes: number,
  costLevel: CostLevel,
  bestTime: TimeOfDay,
  summary: string,
  options?: { intensity?: Intensity; groups?: readonly PlanningGroup[] },
];

function destination(
  id: string,
  name: string,
  country: string,
  timeZone: string,
  rows: readonly Row[],
): CatalogDestination {
  return {
    id,
    name,
    country,
    timeZone,
    activities: rows.map(
      ([slug, title, category, area, typicalMinutes, costLevel, bestTime, summary, options]) => ({
        id: `${id}:${slug}`,
        title,
        category,
        area,
        summary,
        typicalMinutes,
        costLevel,
        bestTime,
        intensity: options?.intensity ?? 'easy',
        groups: options?.groups ?? ALL,
      }),
    ),
  };
}

